#!/usr/bin/env python3
"""Uninstall the Universal UI/UX Engineering suite (V1.3.3).

Only files registered in `uiux-suite/state/install-<version>.json` are removed.
Files shared with another installed version, modified files, and every user
artifact (`.uiux/`, project data) are preserved.

Usage:
    python scripts/uninstall_skill.py --scope user --version 1.3.3
    python scripts/uninstall_skill.py --scope project --project "G:/demo" --version 1.3.3
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import setup_skill as installer  # noqa: E402


def emit(payload: dict, code: int) -> int:
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return code


def load_record(agents_home: Path, version: str) -> dict | None:
    path = installer.record_path(agents_home, version)
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def referenced_by_other(agents_home: Path, version: str) -> set[str]:
    referenced: set[str] = set()
    for record in installer.install_records(agents_home):
        if record.get("version") == version:
            continue
        for entry in record.get("files", []):
            referenced.add(entry["path"])
    return referenced


def prune_empty_dirs(start: Path, stop: Path) -> None:
    current = start
    while current != stop and stop in current.parents:
        try:
            current.rmdir()
        except OSError:
            return
        current = current.parent


def cmd_uninstall(args: argparse.Namespace) -> int:
    agents_home = installer.resolve_agents_home(args.scope, args.project)
    record = load_record(agents_home, args.version)
    if record is None:
        return emit({"ok": False, "code": "INSTALL_RECORD_MISSING", "version": args.version}, 10)

    shared = referenced_by_other(agents_home, args.version)
    removed: list[str] = []
    skipped: list[dict] = []
    missing: list[str] = []
    for entry in record.get("files", []):
        relative = entry["path"]
        target = (agents_home / relative).resolve()
        try:
            target.relative_to(agents_home.resolve())
        except ValueError:
            skipped.append({"path": relative, "reason": "UNAUTHORIZED_PATH"})
            continue
        if not target.is_file():
            missing.append(relative)
            continue
        if relative in shared:
            skipped.append({"path": relative, "reason": "SHARED_WITH_OTHER_VERSION"})
            continue
        if installer.sha256_file(target) != entry["sha256"]:
            skipped.append({"path": relative, "reason": "MODIFIED_FILE_PRESERVED"})
            continue
        target.unlink()
        removed.append(relative)
        prune_empty_dirs(target.parent, agents_home)

    record_file = installer.record_path(agents_home, args.version)
    if record_file.is_file():
        record_file.unlink()

    # Remove runtime-generated bytecode caches inside the versioned suite root.
    suite_root = Path(record.get("suite_root", ""))
    try:
        suite_root.resolve().relative_to(agents_home.resolve())
    except ValueError:
        suite_root = None
    if suite_root and suite_root.is_dir():
        for cache in list(suite_root.rglob("__pycache__")):
            shutil.rmtree(cache, ignore_errors=True)
        for pyc in list(suite_root.rglob("*.pyc")):
            try:
                pyc.unlink()
            except OSError:
                pass
        prune_empty_dirs(suite_root, agents_home)

    remaining = installer.install_records(agents_home)
    relinked: list[str] = []
    if remaining and record.get("activated"):
        newest = max(remaining, key=lambda item: installer.version_tuple(item["version"]))
        suite_root = Path(newest["suite_root"])
        for skill in installer.SKILLS:
            skill_root = agents_home / "skills" / skill
            if not (skill_root / "SKILL.md").is_file():
                continue
            link = installer.suite_link_payload(
                agents_home, suite_root, skill_root, newest["version"], newest.get("python_exe")
            )
            installer.write_json(skill_root / "suite-link.json", link)
            relinked.append(skill)

    return emit(
        {
            "ok": True,
            "version": args.version,
            "removed": len(removed),
            "skipped": skipped,
            "missing": missing,
            "remaining_versions": [item["version"] for item in remaining],
            "relinked": relinked,
        },
        0,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="uninstall_skill.py")
    parser.add_argument("--scope", choices=["user", "project"], default="user")
    parser.add_argument("--project")
    parser.add_argument("--version", required=True)
    args = parser.parse_args(argv)
    return cmd_uninstall(args)


if __name__ == "__main__":
    raise SystemExit(main())
